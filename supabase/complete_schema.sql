-- This script sets up all tables, indexes, and RLS policies required for the 
-- VitaWeave application, including user profiles, patient data, AI insights, 
-- and real-time community health tracking.

-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. USER PROFILES
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    email TEXT UNIQUE,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('asha', 'doctor', 'patient', 'admin')),
    phone TEXT,
    ward TEXT,
    language TEXT DEFAULT 'English',
    avatar_url TEXT,
    level INTEGER DEFAULT 1,
    lives_impacted INTEGER DEFAULT 0,
    hospital_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. HOSPITALS / CLINICS
CREATE TABLE IF NOT EXISTS public.hospitals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    ward TEXT,
    type TEXT DEFAULT 'Government', -- 'Government', 'Private', 'Clinic'
    contact TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Associate profiles with hospitals
ALTER TABLE public.profiles 
ADD CONSTRAINT fk_hospital FOREIGN KEY (hospital_id) REFERENCES public.hospitals(id);

-- 4. PATIENTS
CREATE TABLE IF NOT EXISTS public.patients (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    name TEXT NOT NULL,
    age INTEGER NOT NULL CHECK (age > 0 AND age < 150),
    gender TEXT CHECK (gender IN ('Male', 'Female', 'Other', 'Not Specified')),
    condition TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Stable' CHECK (status IN ('Active', 'Critical', 'Stable', 'Improving', 'Worsening')),
    risk_level TEXT NOT NULL DEFAULT 'Low' CHECK (risk_level IN ('Low', 'Medium', 'High', 'Critical')),
    phone TEXT,
    image_url TEXT,
    ward TEXT,
    last_visit TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    follow_up_due DATE,
    follow_up_urgent BOOLEAN DEFAULT FALSE,
    assigned_asha_id UUID REFERENCES public.profiles(id),
    assigned_doctor_id UUID REFERENCES public.profiles(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. MEDICAL RECORDS
CREATE TABLE IF NOT EXISTS public.medical_records (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    patient_id UUID NOT NULL REFERENCES public.patients(id) ON DELETE CASCADE,
    doctor_id UUID NOT NULL REFERENCES public.profiles(id),
    diagnosis TEXT NOT NULL,
    prescription TEXT,
    notes TEXT,
    vitals JSONB DEFAULT '{}',
    attachments JSONB DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. APPOINTMENTS & TELEMEDICINE
CREATE TABLE IF NOT EXISTS public.appointments (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    patient_id UUID NOT NULL REFERENCES public.patients(id),
    doctor_id UUID NOT NULL REFERENCES public.profiles(id),
    title TEXT NOT NULL,
    description TEXT,
    appointment_time TIMESTAMP WITH TIME ZONE NOT NULL,
    duration INTEGER DEFAULT 30, -- minutes
    status TEXT NOT NULL DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'Active', 'Completed', 'Cancelled', 'No-Show')),
    meeting_link TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. AI CHAT HISTORY
CREATE TABLE IF NOT EXISTS public.ai_chat_history (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id),
    patient_id UUID REFERENCES public.patients(id),
    chat_type TEXT NOT NULL CHECK (chat_type IN ('asha_assistant', 'doctor_diagnostics', 'patient_health')),
    messages JSONB NOT NULL DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. HEALTH & COMMUNITY ALERTS
CREATE TABLE IF NOT EXISTS public.community_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    severity TEXT NOT NULL CHECK (severity IN ('Low', 'Medium', 'High', 'Critical')),
    title TEXT NOT NULL,
